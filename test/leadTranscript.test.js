/**
 * leadTranscript — a compact activity summary of a Claude session for the
 * Chief (lead-agent spec, T05). Pinned: which records count, the event cap,
 * files changed vs read, tail parsing, and the session-file fallback path.
 */

const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');
const T = require('../src/shared/leadTranscript');

const user = (content, extra = {}) => ({ type: 'user', timestamp: 't', message: { role: 'user', content }, ...extra });
const asst = (content, extra = {}) => ({ type: 'assistant', timestamp: 't', message: { role: 'assistant', content }, ...extra });

const RECORDS = [
  { type: 'summary', summary: 'old summary' },
  user('<command-name>/clear</command-name>'),
  user('Caveat: The messages below were generated by the user while running local commands.'),
  user('Fix the flaky login test'),
  user([{ type: 'text', text: '<system-reminder>ctx</system-reminder>' }], { isMeta: true }),
  asst([{ type: 'text', text: 'Looking at the test.' }, { type: 'tool_use', name: 'Read', input: { file_path: 'test/login.test.js' } }]),
  user([{ type: 'tool_result', content: 'file body' }]),
  asst([{ type: 'tool_use', name: 'Edit', input: { file_path: 'src/auth/login.js' } }, { type: 'tool_use', name: 'Bash', input: { command: 'npm test -- login' } }]),
  asst([{ type: 'tool_use', name: 'Read', input: { file_path: 'src/auth/login.js' } }]),
  asst([{ type: 'text', text: 'Subagent noise' }], { isSidechain: true }),
  { type: 'ai-title', aiTitle: 'Fix flaky login test' },
  asst([{ type: 'text', text: 'The test was racing the session store; fixed and green.' }])
];

test('summary: title, last prompt, events in order, files changed vs read', () => {
  const s = T.summarize(RECORDS);
  assert.equal(s.title, 'Fix flaky login test', 'ai-title wins over an older summary');
  assert.equal(s.lastPrompt, 'Fix the flaky login test');
  assert.deepEqual(s.events.map((e) => `${e.type}: ${e.text}`), [
    'prompt: Fix the flaky login test',
    'reply: Looking at the test.',
    'tool: Read test/login.test.js',
    'tool: Edit src/auth/login.js',
    'tool: Bash: npm test -- login',
    'tool: Read src/auth/login.js',
    'reply: The test was racing the session store; fixed and green.'
  ]);
  assert.deepEqual(s.filesChanged, ['src/auth/login.js']);
  assert.deepEqual(s.filesRead, ['test/login.test.js'], 'a changed file is not also listed as read');
  assert.equal(s.truncated, false);
});

test('summary keeps only the last N events and says so', () => {
  const many = Array.from({ length: 25 }, (_, i) => user(`prompt ${i}`));
  const s = T.summarize(many, { maxEvents: 10 });
  assert.equal(s.events.length, 10);
  assert.equal(s.events[0].text, 'prompt 15');
  assert.equal(s.truncated, true);
  assert.equal(T.DEFAULT_EVENTS, 10);
});

test('long text is excerpted, junk is tolerated', () => {
  const s = T.summarize([user('x'.repeat(1000)), null, 'str', { type: 'assistant', message: { content: 'not an array' } }]);
  assert.equal(s.events.length, 1);
  assert.ok(s.events[0].text.length <= 280);
  assert.ok(s.events[0].text.endsWith('…'));
  assert.deepEqual(T.summarize(undefined).events, []);
});

test('parseLines drops the partial first line of a tail read and bad lines', () => {
  const text = 'ial":1}\n{"a":1}\nnot json\n\n{"b":2}\n{"c":';
  assert.deepEqual(T.parseLines(text, { fromMiddle: true }), [{ a: 1 }, { b: 2 }]);
  assert.deepEqual(T.parseLines('{"a":1}\n'), [{ a: 1 }]);
});

test('session-file fallback builds the transcript path, or gives up', () => {
  const enc = (p) => p.replace(/[^a-zA-Z0-9]/g, '-');
  const opts = { projectsDir: '/h/.claude/projects', encodeProjectPath: enc, join: path.posix.join };
  const sid = '00000000-0000-4000-8000-000000000001';
  assert.equal(T.transcriptPathFromSession({ pid: 1, sessionId: sid, cwd: '/Users/k/frame/workspaces/X/violet' }, opts),
    `/h/.claude/projects/-Users-k-frame-workspaces-X-violet/${sid}.jsonl`);
  assert.equal(T.transcriptPathFromSession({ sessionId: '../../etc/passwd', cwd: '/x' }, opts), null, 'only a UUID becomes a file name');
  assert.equal(T.transcriptPathFromSession({ sessionId: sid }, opts), null);
  assert.equal(T.transcriptPathFromSession(null, opts), null);
  assert.equal(T.transcriptPathFromSession({ sessionId: sid, cwd: '/x' }, { ...opts, projectsDir: null }), null);
});
